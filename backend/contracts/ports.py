"""Public Python ports; integrations own transport, execution and lifecycle."""

from dataclasses import dataclass
from typing import Any, Literal, Mapping, Protocol

JobState = Literal["pending", "submitting", "submitted", "running", "fetching", "succeeded", "failed", "needs_recovery", "unknown", "cancelled"]


@dataclass(frozen=True)
class ProviderCapabilities:
    provider_id: str
    available: bool
    unavailable_reason: str | None = None
    local: bool = False
    query: bool = False
    cancel: bool = False
    idempotency_lookup: bool = False


class JobPort(Protocol):
    def create_or_get(self, request_id: str, *, provider: str, execution_kind: str, snapshot: dict, source: dict | None = None) -> tuple[dict, bool]: ...
    def get(self, request_id: str) -> dict: ...
    def begin_submission(self, request_id: str, *, expected_version: int) -> dict: ...
    def mark_submitted(self, request_id: str, provider_task_id: str, *, expected_version: int, event_id: str) -> dict: ...
    def transition(self, request_id: str, state: JobState, *, expected_version: int, event_id: str, provider_task_id: str | None = None, result: dict | None = None, error_code: str | None = None) -> dict: ...
    def recovery_action(self, request_id: str, *, supports_query: bool = False, supports_idempotency_lookup: bool = False) -> dict: ...
    def request_cancel(self, request_id: str, *, expected_version: int, supports_remote_cancel: bool = False) -> dict: ...


class AssetPort(Protocol):
    def get(self, asset_id: str) -> dict: ...
    def register_file(self, root_key: str, relative_path: str, *, kind: str, provenance: Mapping[str, Any] | None = None) -> dict: ...
    def register_text(self, text: str, *, provenance: Mapping[str, Any] | None = None) -> dict: ...
    def freeze(self, reference_id: str) -> dict: ...
    def validate_reference(self, reference_id: str) -> dict: ...
    def validate_result_receipt(self, receipt: dict) -> bool: ...
    def import_legacy_favorites(self, *, origin: str, entries: list[dict]) -> list[dict]: ...
    def search(self, query: str = "", *, kind: str | None = None, limit: int = 100, offset: int = 0) -> list[dict]: ...
